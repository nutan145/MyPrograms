package com.nutan.string;

public class charAt {

	public static void main(String[] args) 
	{
		String str="Naresh It";
		char ch = str.charAt(3);
		System.out.println("Character at 3rd position :"+ch);
		
		
		String s1="Hyderabad";
		char ch1 = s1.charAt(4);
		System.out.println("Character at 4th position :"+ch1);
	}

}
